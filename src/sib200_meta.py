"""SIB-200 reference metadata -- the single source of truth for language groups.

Ported from the legacy XPE repo's `meta.csv`
(`nlpka/datasets/storage/benchmarks/text_classification/topic/
sib200_tokenized_xlmr/meta.csv`), which drove every source and target group in
the published paper. Held as a Python literal rather than a CSV: `artefacts/` is
gitignored (so it cannot hold anything tests depend on) and `scripts/` holds
code, not data.

Columns
-------
class     Joshi et al. (2020) resource tier; `class == 5` is the Joshi5 group.
xlmr      1 = in XLM-R's CC100 pretraining set. 92 of the 205 -> the paper's
          "Seen" group (xpe.pdf sec. 4.2: "The 92 languages that were included
          in the XLM-R pretraining corpus").
          CAVEAT: this column is published provenance, not a re-derivation of
          XLM-R's official tag list, and it disagrees with that list on exactly
          two codes -- `tgl_Latn` is marked 0 although XLM-R lists `tl`, and
          `azb_Arab` is marked 1 although XLM-R lists only `az` (= azj_Latn).
          The two errors offset, which is why the count is 92. Do NOT "fix"
          them: the paper's Seen-92 and every published number depend on this
          exact column.
low_perf  PROVENANCE ONLY -- see low_perf_langs(). 1 = the paper's
          Low-Performing group (46 languages), extracted from
          the appendix per-language tables (xpe.pdf pp. 12-14, Group == 2;
          legend on p. 14: "2 = Low-Performing and Unseen, 1 = Unseen,
          0 = Seen /wo Joshi5"). Defined in sec. 4.2 as SIB-200 languages
          scoring below 60% under full fine-tuning of XLM-R-large in the
          original benchmark -- i.e. BENCHMARK-derived, not backbone-derived,
          so it is the same list for every backbone. It is a strict subset of
          Unseen (verified: its intersection with `xlmr == 1` is empty).
          Self-check: 46 low-perf + 67 unseen-not-low-perf + 85 seen-wo-joshi5
          = 198 = 205 - 7 joshi5, and 85 + 7 = the Seen-92.

Source-language GROUPS are not defined here. `LANG_GROUPS` in
`scripts/run_xlt.py` is the single runtime source of truth for every group;
`tests/test_lang_groups.py` pins its literals against this table so the two
cannot drift. What this module is for: the per-language metadata behind those
groups (Joshi tier, family, region, and which backbone saw what).

Backbone seen-sets:
  mdeberta  mDeBERTa-v3 trains on CC100 like XLM-R, so LANG_GROUPS['mdeberta_seen']
            is the `xlmr` set. ASSUMPTION, not documented fact: the model
            card (https://huggingface.co/microsoft/mdeberta-v3-base) says
            "trained using the 2.5T CC100 data as XLM-R" and the DeBERTaV3
            paper says "using a similar setting as XLM-R"; neither states an
            identical language list, and mDeBERTa uses mT5's 250k vocabulary,
            not XLM-R's. The bridge-row claim rests on this assumption -- state
            it in the write-up rather than asserting an identical corpus.
  mgte      Membership in MGTE_TOKENS_M: mGTE's 75 MLM-pretraining languages
            (Zhang et al. 2024, arXiv:2407.19669 Table 7, App. A.1), all of
            which land in SIB-200. 76 codes because Chinese counts as one
            language there but is two codes here -- the table caption's own
            convention, and the same one LANG_GROUPS['aya_seen'] uses.
"""

